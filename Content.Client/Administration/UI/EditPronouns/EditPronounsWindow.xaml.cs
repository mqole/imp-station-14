using System.Linq;
using System.Numerics;
using Content.Shared.Pronouns;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects.Components.Localization;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client.Administration.UI.EditPronouns;

/// <summary>
///     Admin Eui window to view or edit an entity's pronouns.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class EditPronounsWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _protoMan = default!;

    private readonly GrammarSystem _grammar = default!;

    private NetEntity _target = NetEntity.Invalid;

    /// <summary>
    ///     Cached pronouns for this entity.
    ///     Will always attempt to use the target's <see cref="GrammarComponent"/> pronouns.
    /// </summary>
    private Dictionary<ProtoId<PronounGrammarPrototype>, string> _pronouns = [];

    /// <summary>
    ///     List of inflections that have been removed pending 'reset changes' or 'save changes'.
    ///     Stored so we can re-add them if needed.
    /// </summary>
    private List<ProtoId<PronounGrammarPrototype>> _removedPronouns = [];

    private List<PronounGrammarPrototype> _unusedInflections = [];
    private List<PronounSetPrototype> _presets = [];

    public Action<(NetEntity target, Dictionary<ProtoId<PronounGrammarPrototype>, string> pronouns)>? OnSaveMessage;

    public EditPronounsWindow()
    {
        IoCManager.InjectDependencies(this);
        _grammar = _entityManager.System<GrammarSystem>();
        RobustXamlLoader.Load(this);

        foreach (var pronounSet in _protoMan.EnumeratePrototypes<PronounSetPrototype>())
        {
            PresetDropdown.AddItem(pronounSet.Name);
            _presets.Add(pronounSet);
        }

        PresetDropdown.OnItemSelected += SetPreset;
        AddButton.OnPressed += AddPressed;
        RemoveDropdownButton.OnPressed += RemoveDropdown;
        NewDropdown.OnItemSelected += SetNewPronoun;
        ResetButton.OnPressed += ResetPressed;
        SaveButton.OnPressed += SavePressed;
    }

    /// <summary>
    ///     Assigns the target of this editor window.
    /// </summary>
    public void SetTargetEntity(NetEntity target)
    {
        _target = target;
        var uid = _entityManager.GetEntity(target);

        var targetName = _entityManager.EntityExists(uid)
                ? _entityManager.GetComponent<MetaDataComponent>(uid).EntityName
                : string.Empty;

        Title = Loc.GetString("edit-pronouns-title", ("targetName", targetName));
    }

    /// <summary>
    ///     Sets the list of pronouns in the ui using provided dictionary.
    /// </summary>
    public void SetPronouns(Dictionary<ProtoId<PronounGrammarPrototype>, string> pronouns)
    {
        PronounContainer.DisposeAllChildren();

        foreach (var pronoun in pronouns)
            AddPronounEntry(pronoun);
    }

    private void AddPronounEntry(KeyValuePair<ProtoId<PronounGrammarPrototype>, string> pronoun)
    {
        // ensure we arent adding a pronoun that already exists
        if (PronounContainer.Children.Any(x => x is PronounEntry p && p.Inflection == pronoun.Key))
            return;

        var entry = new PronounEntry(pronoun);
        entry.OnRemove += args =>
        {
            PronounContainer.RemoveChild(entry);
            _removedPronouns.Add(entry.Inflection);
        };
        entry.InflectionLabel.ToolTip = Loc.GetString(_protoMan.Index(pronoun.Key).Description);

        PronounContainer.AddChild(entry);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!_entityManager.TryGetEntity(_target, out var uid) ||
            !_entityManager.TryGetComponent<GrammarComponent>(uid, out var grammar))
        {
            return;
        }

        // ensure that cached pronouns match the pronouns of the entity
        // if theyre different, we've received an update, so refresh the pronouns shown on the ui
        if (_grammar.TryGetPronouns((uid.Value, grammar), out var pronouns) &&
            (pronouns.Count != _pronouns.Count ||
            pronouns.Except(_pronouns).Any()))
        {
            _pronouns = pronouns;
            SetPronouns(pronouns);
        }
    }

    private void SetPreset(OptionButton.ItemSelectedEventArgs args)
    {
        var selected = args.Id;
        SetPronouns(_presets[selected].GetPronouns());
    }

    /// <summary>
    ///     Adds a new dropdown to the list from which a new inflection may be selected.
    /// </summary>
    private void AddPressed(BaseButton.ButtonEventArgs args)
    {
        _unusedInflections.Clear();
        NewDropdown.Clear();

        // dropdown should only show inflections that we dont have!
        var protos = _protoMan.EnumeratePrototypes<PronounGrammarPrototype>().ToList();
        foreach (var child in PronounContainer.Children)
        {
            if (child is not PronounEntry entry)
                continue;
            protos.Remove(_protoMan.Index(entry.Inflection));
        }

        foreach (var inflection in protos)
        {
            NewDropdown.AddItem(Loc.GetString(inflection.Name));
            _unusedInflections.Add(inflection);
        }

        ToggleAddDropdown(true);
    }

    /// <summary>
    ///     Re-hides the 'add' dropdown.
    /// </summary>
    private void RemoveDropdown(BaseButton.ButtonEventArgs args)
    {
        ToggleAddDropdown(false);
    }

    /// <summary>
    ///     Adds the selected option in the dropdown as a new pronoun
    /// </summary>
    private void SetNewPronoun(OptionButton.ItemSelectedEventArgs args)
    {
        var inflection = _unusedInflections[args.Id];
        var pronoun = new KeyValuePair<ProtoId<PronounGrammarPrototype>, string>(inflection.ID, "");

        AddPronounEntry(pronoun);

        ToggleAddDropdown(false);
        _removedPronouns.Remove(inflection.ID);
    }

    private void ToggleAddDropdown(bool visible)
    {
        NewDropdown.Visible = visible;
        RemoveDropdownButton.Visible = visible;
        AddButton.Disabled = visible;
    }

    /// <summary>
    ///     When edits are saved, update cached pronouns and set pronouns for the target entity.
    /// </summary>
    private void SavePressed(BaseButton.ButtonEventArgs args)
    {
        Dictionary<ProtoId<PronounGrammarPrototype>, string> newPronouns = [];

        foreach (var child in _removedPronouns)
            newPronouns.Add(child, "");

        foreach (var child in PronounContainer.Children)
        {
            if (child is not PronounEntry entry)
                continue;

            var pronoun = entry.PronounLineEdit.Text == "" &&
                entry.PronounLineEdit.PlaceHolder is { } placeholder ?
                placeholder : entry.PronounLineEdit.Text;

            newPronouns.Add(entry.Inflection, pronoun);
        }

        OnSaveMessage?.Invoke((_target, newPronouns));
        _removedPronouns.Clear();
    }

    /// <summary>
    ///     Resets any edited values.
    /// </summary>
    private void ResetPressed(BaseButton.ButtonEventArgs args)
    {
        SetPronouns(_pronouns);
        _removedPronouns.Clear();
    }
}
